export const CANONICAL_SKILLS = Object.keys(SKILL_ALIASES);

export function normalizeSkill(s) {
  const v = String(s).trim().toLowerCase();
  for (const [canon, aliases] of Object.entries(SKILL_ALIASES)) {
    if (canon === v) return canon;
    if (aliases.some((a) => a === v || v.includes(a) || a.includes(v))) return canon;
  }
  return v;
}